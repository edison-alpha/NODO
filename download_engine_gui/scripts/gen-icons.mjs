/**
 * The icon's markup on the shared SIZE grid. One from another set keeps its
 * own grid inside a nested <svg> scaled up to fill it, so <Icon> needs only
 * one viewBox.
 */
function body(ref) {
  const [prefix, id] = ref.includes(":") ? ref.split(":") : ["f7", ref];
  const source = prefix === "f7" ? set : require(`@iconify-json/${prefix}/icons.json`);
  const icon = source.icons[id] ?? source.icons[source.aliases?.[id]?.parent];
  if (!icon) throw new Error(`${prefix}:${id} not found`);
  const w = icon.width ?? source.width ?? 16;
  const h = icon.height ?? source.height ?? 16;
  if (w === SIZE && h === SIZE) return icon.body;
  return `<svg viewBox="0 0 ${w} ${h}" width="${SIZE}" height="${SIZE}">${icon.body}</svg>`;
}

const lines = Object.entries(MAP).map(([name, ref]) => `  ${name}: ${JSON.stringify(body(ref))},`);

const out = `// Generated by scripts/gen-icons.mjs from @iconify-json/f7 (MIT, Vladimir Kharlampidi),
// with queue from Heroicons (MIT) and apps from Fluent UI System Icons (MIT).
// SF Symbols-style icons; edit the map in the script, not this file.
export const ICON_VIEWBOX = ${SIZE};

export const ICONS = {
${lines.join("\n")}
} as const;

export type IconName = keyof typeof ICONS;
`;

writeFileSync(fileURLToPath(new URL("../src/lib/icon-data.ts", import.meta.url)), out);
console.log(`wrote ${lines.length} icons`);
